#!/bin/bash
# Writes the installer settings for bootc-image-builder to the file given as $1.
#
# The installer system itself is stock Fedora and cannot be changed from here, so the
# KantanOS artwork travels inside the kickstart: a %pre script (which runs before the
# installer window opens) drops the logo and stylesheet into place. The script is Python
# because the installer system has no base64 tool but always has Python.
set -euo pipefail
OUT=${1:?usage: make-iso-config.sh <output.toml>}
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
LOGO=$(mktemp --suffix=.png)
# Logo in the default look's colours (tools/looks.py writes branding/default/).
rsvg-convert -w 220 "$ROOT/branding/default/kantanos-logo-stacked-on-dark.svg" -o "$LOGO"

{
cat <<'TOML'
# Generated by tools/iso/make-iso-config.sh - do not edit.

# Pages the installer shows in addition to disk and user: language, keyboard, time zone.
[customizations.installer.modules]
enable = [
  "org.fedoraproject.Anaconda.Modules.Localization",
  "org.fedoraproject.Anaconda.Modules.Timezone",
]

[customizations.installer.kickstart]
contents = '''
# Graphical boot with the KantanOS splash on the installed system
bootloader --append="rhgb quiet"

# Keyboard defaults to US English (Japanese is typed through the input method, not a
# layout). The Keyboard page stays available for anyone who needs another layout.
# Language and time zone are deliberately not preset: the installer asks for them.
keyboard --xlayouts='us'

# KantanOS look for the installer (runs before the installer window opens)
%pre --interpreter=/usr/bin/python3
import base64, os
P = "/usr/share/anaconda/pixmaps"
os.makedirs(P, exist_ok=True)
LOGO = """
TOML
base64 -w 76 "$LOGO"
cat <<'TOML'
"""
CSS = """/* KantanOS installer style */
@define-color kantan_dark #0b0e17;

.logo-sidebar {
    background-image: linear-gradient(to bottom, #171d36, #0b0e17);
    background-color: @kantan_dark;
    background-repeat: no-repeat;
}
.logo {
    background-image: url('/usr/share/anaconda/pixmaps/kantanos-logo.png');
    background-position: 50% 28px;
    background-repeat: no-repeat;
    background-color: transparent;
}
.product-logo {
    background-image: none;
    background-color: transparent;
}
AnacondaSpokeWindow #nav-box {
    background-image: linear-gradient(to right, #171d36, #3a41a8);
    background-color: @kantan_dark;
    color: white;
}
"""
with open(P + "/kantanos-logo.png", "wb") as f:
    f.write(base64.b64decode(LOGO))
with open(P + "/fedora.css", "w") as f:
    f.write(CSS)
%end
'''
TOML
} > "$OUT"
rm -f "$LOGO"
echo "installer config: $OUT ($(wc -c < "$OUT") bytes)"
